import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import net from 'node:net';
import { spawn, execFileSync } from 'node:child_process';
import { createHash, randomBytes } from 'node:crypto';
import { once } from 'node:events';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { installKit } from '../install-kit.mjs';
const source = fileURLToPath(new URL('../', import.meta.url));
test('Codex stdio bridge authenticates with local Git settings and forwards tools and branch', async t => {
 const temp=await fs.mkdtemp(path.join(os.tmpdir(),'agentstalk-proxy-'));t.after(()=>fs.rm(temp,{recursive:true,force:true}));
 const root=path.join(temp,'repo'),data=path.join(temp,'data');await fs.mkdir(root);await fs.mkdir(data);
 const git=(...args)=>execFileSync('git',args,{cwd:root,encoding:'utf8',stdio:['ignore','pipe','pipe']}).trim();
 git('init','-q','--initial-branch=main');git('remote','add','origin','https://github.com/team/hackathon');
 const key=randomBytes(32).toString('hex');
 await fs.writeFile(path.join(data,'state.json'),JSON.stringify({projects:{},keys:{[createHash('sha256').update(key).digest('hex')]:{login:'friend',project:'team/hackathon',createdAt:Date.now()}}}));
 const portServer=net.createServer();await new Promise(r=>portServer.listen(0,'127.0.0.1',r));const port=portServer.address().port;await new Promise(r=>portServer.close(r));
 const url=`http://127.0.0.1:${port}`;
 const child=spawn(process.execPath,[path.join(source,'server.mjs')],{env:{...process.env,PORT:String(port),AGENT_HUB_DATA_DIR:data,AGENT_HUB_TOKEN:''},stdio:'ignore'});
 t.after(async()=>{if(child.exitCode===null){const done=once(child,'exit');child.kill();await done;}});
 let ready=false;for(let i=0;i<100;i++){try{if((await fetch(url+'/api/config')).ok){ready=true;break;}}catch{}await new Promise(r=>setTimeout(r,50));}assert.ok(ready,'hub started');
 await installKit(root,url);git('config','agenthub.url',url);git('config','agenthub.key',key);
 const client=new Client({name:'codex-test',version:'1.0.0'});
 const transport=new StdioClientTransport({command:process.execPath,args:['agentstalk/mcp-proxy.mjs'],cwd:root,stderr:'pipe'});
 t.after(()=>client.close());await client.connect(transport);
 const tools=await client.listTools();assert.equal(tools.tools.length,8);
 const status=await client.callTool({name:'status',arguments:{}});assert.match(status.content[0].text,/friend-agent/);
 const locked=await client.callTool({name:'lock_files',arguments:{paths:['app.js'],reason:'proxy integration'}});assert.match(locked.content[0].text,/Locked for you/);
 const response=await fetch(url+'/api/state',{headers:{authorization:`Bearer ${key}`}});const state=await response.json();assert.equal(state.locks[0].branch,'main');assert.equal(state.locks[0].owner,'friend-agent');
 const unlock=await client.callTool({name:'unlock_files',arguments:{paths:['app.js']}});assert.match(unlock.content[0].text,/Released/);
});
